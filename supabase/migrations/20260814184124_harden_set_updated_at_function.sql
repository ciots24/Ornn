-- A trigger that only stamps a timestamp needs no elevated rights, and it has
-- no business being callable over the REST API. Drop the elevation and take
-- EXECUTE away from the public roles.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

revoke all on function public.set_updated_at() from public;
revoke all on function public.set_updated_at() from anon;
revoke all on function public.set_updated_at() from authenticated;
